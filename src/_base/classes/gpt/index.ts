import OpenAI from 'openai';

type Prompts = { topic: string; grade: string };
type ToolPrompts = { tools: string[]; previousResponse: string };

export interface AutoGeneratedContent {
  title: string;
  objective: string;
  materials: string[];
  steps: Array<{ title: string; description: string; position: number }>;
  bncc: Array<Record<string, string>>;
  bnccTags: string[];
}

export type AutoGeneratedMetadata = { content: AutoGeneratedContent; used_tokens?: number };

export interface AutoGenerateResponse {
  ai_model: string;
  total_used_tokens?: number;
  answer: Omit<AutoGeneratedMetadata, 'content'> & { content: string };
  response: AutoGeneratedMetadata;
}

type RawGenerateFuncType = (data: Prompts) => Promise<AutoGenerateResponse>;
type ToolsGenerateFuncType = (data: ToolPrompts) => Promise<string[]>;

